function renderGlyphCanvas(ch, fontFamily, colorHex) {
  const canvas = document.createElement("canvas");
  canvas.width = GLYPH_CANVAS_SIZE;
  canvas.height = GLYPH_CANVAS_SIZE;
  const ctx = canvas.getContext("2d");
  ctx.font = `900 ${GLYPH_REF_SIZE}px ${fontFamily}`;
  ctx.textBaseline = "alphabetic";
  ctx.textAlign = "left";
  ctx.fillStyle = colorHex;
  ctx.fillText(ch, GLYPH_BASELINE_X, GLYPH_BASELINE_Y);
  return canvas;
}

function findInkBoundingBox(canvas) {
  const ctx = canvas.getContext("2d");
  const { width, height } = canvas;
  const data = ctx.getImageData(0, 0, width, height).data;
  let minX = width,
    minY = height,
    maxX = -1,
    maxY = -1;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (data[(y * width + x) * 4 + 3] > 10) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  if (maxX < minX || maxY < minY) return null;
  return { x: minX, y: minY, width: maxX - minX + 1, height: maxY - minY + 1 };
}

function getGlyphBitmap(ch, fontFamily, colorHex) {
  const key = `${ch}|${fontFamily}|${colorHex}`;
  if (_glyphCache.has(key)) return _glyphCache.get(key);
  const canvas = renderGlyphCanvas(ch, fontFamily, colorHex);
  const bbox = findInkBoundingBox(canvas);
  const result = bbox ? { canvas, bbox } : null;
  _glyphCache.set(key, result);
  return result;
}

function drawScaledGlyph(ctx, ch, x, y, targetWidth, targetHeight, colorHex, fontFamily) {
  const glyph = getGlyphBitmap(ch, fontFamily, colorHex);
  if (!glyph) return;
  const { canvas, bbox } = glyph;
  ctx.drawImage(canvas, bbox.x, bbox.y, bbox.width, bbox.height, x, y, targetWidth, targetHeight);
}

function computeColumnLogoInfo(column, alphabetKeys, alphabetSize, useError) {
  let sampleSize = 0;
  column.forEach((ch) => {
    if (ch !== "-") sampleSize++;
  });
  const freq = {};
  alphabetKeys.forEach((c) => {
    let count = 0;
    for (const ch of column) if (ch === c) count++;
    freq[c] = sampleSize > 0 ? count / sampleSize : 0;
  });
  let uncertainty = 0;
  alphabetKeys.forEach((c) => {
    const f = freq[c];
    if (f > 0) uncertainty += f * Math.log2(f);
  });
  uncertainty = -uncertainty;
  const errest = useError && sampleSize > 0 ? ((1 / Math.LN2) * (alphabetSize - 1)) / (2 * sampleSize) : 0;
  let infoContent = Math.log2(alphabetSize) - (uncertainty + errest);
  infoContent = Math.max(infoContent, 0);
  return { freq, infoContent };
}

function drawLogoColumn(ctx, column, colorMap, alphabetKeys, alphabetSize, index, useError, fontFamily, geom) {
  const { freq, infoContent } = computeColumnLogoInfo(column, alphabetKeys, alphabetSize, useError);
  const maxInfo = Math.log2(alphabetSize);
  const actualWorkingHeight = (maxInfo / Math.ceil(maxInfo)) * geom.workingHeight;
  const columnWorkingHeight = maxInfo > 0 ? (infoContent / maxInfo) * actualWorkingHeight : 0;

  const entries = alphabetKeys
    .map((ch) => ({ ch, height: freq[ch] * columnWorkingHeight }))
    .filter((e) => e.height > 0.05)
    .sort((a, b) => a.height - b.height);

  const xval = geom.ORIGIN_X + geom.characterWidth * index;
  let yval = geom.ORIGIN_Y + geom.workingHeight;
  entries.forEach((e) => {
    yval -= e.height;
    drawScaledGlyph(ctx, e.ch, xval, yval, geom.characterWidth, e.height, colorMap[e.ch] || "#000000", fontFamily);
  });
}

function drawLogoAxes(ctx, maxBits, len, geom, fontFamily) {
  ctx.fillStyle = "#000000";
  ctx.fillRect(geom.ORIGIN_X - geom.AXIS_WIDTH, geom.ORIGIN_Y, geom.AXIS_WIDTH, geom.workingHeight + geom.AXIS_WIDTH);
  ctx.fillRect(
    geom.ORIGIN_X - geom.AXIS_WIDTH,
    geom.ORIGIN_Y + geom.workingHeight,
    geom.characterWidth * len + geom.AXIS_WIDTH,
    geom.AXIS_WIDTH
  );

  const xpostickx = geom.ORIGIN_X - 2 * geom.AXIS_WIDTH;
  ctx.font = `bold 12px ${fontFamily}`;
  ctx.textAlign = "right";
  ctx.textBaseline = "middle";
  for (let k = 0; k <= maxBits; k++) {
    const fraction = k / maxBits;
    const yposk = fraction * geom.workingHeight + geom.ORIGIN_Y;
    ctx.fillRect(xpostickx, yposk, geom.AXIS_WIDTH, geom.AXIS_WIDTH);
    ctx.fillText(String(maxBits - k), xpostickx - 4, yposk);
  }

  ctx.save();
  ctx.translate(geom.ORIGIN_X - 26, geom.ORIGIN_Y + geom.workingHeight / 2);
  ctx.rotate(-Math.PI / 2);
  ctx.textAlign = "center";
  ctx.textBaseline = "bottom";
  ctx.fillText("bits", 0, 0);
  ctx.restore();

  ctx.textAlign = "center";
  ctx.textBaseline = "top";
  const yposxlabs = geom.ORIGIN_Y + geom.workingHeight + geom.AXIS_WIDTH + 4;
  for (let k = 1; k <= len; k++) {
    const xposxlab = geom.ORIGIN_X + (k - 1) * geom.characterWidth + geom.characterWidth / 2;
    ctx.fillText(String(k), xposxlab, yposxlabs);
  }
}

// ---------- Simple fixed-row track renderer (annotation / numbering / consensus) ----------
function initTrackRenderer(canvas, wrapperEl, config) {
  const dpr = window.devicePixelRatio || 1;
  let { w: CELL_W, h: CELL_H } = config.getCellDims();

  function sizeCanvas() {
    const rowCount = config.getRowCount();
    canvas.width = wrapperEl.clientWidth * dpr;
    canvas.height = rowCount * CELL_H * dpr;
    canvas.style.width = wrapperEl.clientWidth + "px";
    canvas.style.height = rowCount * CELL_H + "px";
  }
  sizeCanvas();

  const gl = canvas.getContext("webgl2");
  if (!gl) {
    alert("WebGL2 not supported");
    return {
      onScroll() {},
      onResize() {},
      rebuildBuffer() {},
      onRowCountChanged() {},
      setCellSize() {},
      setLuminance() {},
      setHoverCol() {},
      setSelection() {}
    };
  }

  const { prog, vao, atlasTex, instBuf, uni } = compileMsaProgram(gl);
  gl.useProgram(prog);
  gl.uniform2f(uni.cellSize, CELL_W * dpr, CELL_H * dpr);
  gl.uniform2f(uni.scroll, 0, 0);
  gl.uniform2f(uni.res, canvas.width, canvas.height);
  gl.uniform1f(uni.luminance, config.getLuminance());

  let instData = null;
  let instanceCount = 0;
  let currentScrollX = 0;
  let hoveredIdx = -1;

  function rebuild() {
    const rowCount = config.getRowCount();
    const colCount = config.getColCount();
    instanceCount = rowCount * colCount;
    instData = buildInstanceArray(rowCount, colCount, config.cellForFn);
    gl.bindBuffer(gl.ARRAY_BUFFER, instBuf);
    gl.bufferData(gl.ARRAY_BUFFER, instData, gl.DYNAMIC_DRAW);
  }
  rebuild();

  function pick(clientX, clientY) {
    const rect = canvas.getBoundingClientRect();
    const x = (clientX - rect.left) * dpr + currentScrollX;
    const y = (clientY - rect.top) * dpr;
    const colCount = config.getColCount();
    const col = Math.floor(x / (CELL_W * dpr));
    const row = Math.floor(y / (CELL_H * dpr));
    if (row < 0 || row >= config.getRowCount() || col < 0 || col >= colCount) return null;
    return { row, col, idx: row * colCount + col };
  }

  if (config.editable) {
    canvas.addEventListener("click", (e) => {
      if (window._activeContextMenu) {
        closeContextMenu();
        return;
      }
      const cell = pick(e.clientX, e.clientY);
      if (!cell) return;
      config.onEdit(cell.row, cell.col, e.clientX, e.clientY);
    });
  }

  canvas.addEventListener("mousemove", (e) => {
    const cell = pick(e.clientX, e.clientY);
    const newIdx = cell ? cell.idx : -1;
    if (newIdx !== hoveredIdx) {
      if (hoveredIdx >= 0 && instData) instData[hoveredIdx * 7 + 5] = 0;
      if (newIdx >= 0 && instData) instData[newIdx * 7 + 5] = 1;
      hoveredIdx = newIdx;
      if (instData) {
        gl.bindBuffer(gl.ARRAY_BUFFER, instBuf);
        gl.bufferData(gl.ARRAY_BUFFER, instData, gl.DYNAMIC_DRAW);
      }
    }
    if (cell && config.onHover) config.onHover(cell.row, cell.col);
    else if (!cell && config.onHoverEnd) config.onHoverEnd();
  });
  canvas.addEventListener("mouseleave", () => {
    if (hoveredIdx >= 0 && instData) {
      instData[hoveredIdx * 7 + 5] = 0;
      hoveredIdx = -1;
      gl.bindBuffer(gl.ARRAY_BUFFER, instBuf);
      gl.bufferData(gl.ARRAY_BUFFER, instData, gl.DYNAMIC_DRAW);
    }
    if (config.onHoverEnd) config.onHoverEnd();
  });

  function render() {
    gl.viewport(0, 0, canvas.width, canvas.height);
    gl.clearColor(0.07, 0.07, 0.07, 1);
    gl.clear(gl.COLOR_BUFFER_BIT);
    gl.useProgram(prog);
    gl.activeTexture(gl.TEXTURE0);
    gl.bindTexture(gl.TEXTURE_2D, atlasTex);
    gl.bindVertexArray(vao);
    gl.drawArraysInstanced(gl.TRIANGLES, 0, 6, instanceCount);
    requestAnimationFrame(render);
  }
  render();

  return {
    onScroll(scrollLeft) {
      currentScrollX = scrollLeft * dpr;
      gl.useProgram(prog);
      gl.uniform2f(uni.scroll, currentScrollX, 0);
    },
    onResize() {
      sizeCanvas();
      gl.useProgram(prog);
      gl.uniform2f(uni.res, canvas.width, canvas.height);
    },
    rebuildBuffer() {
      rebuild();
    },
    onRowCountChanged() {
      sizeCanvas();
      rebuild();
      gl.useProgram(prog);
      gl.uniform2f(uni.res, canvas.width, canvas.height);
    },
    applyColorOverrides(hitList) {
      const colCount = config.getColCount();
      hitList.forEach(({ row, col, ch, color }) => {
        const idx = row * colCount + col;
        if (ch !== undefined) instData[idx * 7 + 6] = glyphIndexFor(ch);
        instData[idx * 7 + 2] = color[0];
        instData[idx * 7 + 3] = color[1];
        instData[idx * 7 + 4] = color[2];
      });
      gl.bindBuffer(gl.ARRAY_BUFFER, instBuf);
      gl.bufferData(gl.ARRAY_BUFFER, instData, gl.DYNAMIC_DRAW);
    },
    setCellSize(newW, newH) {
      CELL_W = newW;
      CELL_H = newH;
      gl.useProgram(prog);
      gl.uniform2f(uni.cellSize, CELL_W * dpr, CELL_H * dpr);
      sizeCanvas();
      gl.uniform2f(uni.res, canvas.width, canvas.height);
    },
    setLuminance(val) {
      gl.useProgram(prog);
      gl.uniform1f(uni.luminance, val);
    },
    setHoverCol(col) {
      gl.useProgram(prog);
      gl.uniform1f(uni.hoverCol, col);
    },
    setSelection(startCol, endCol) {
      gl.useProgram(prog);
      gl.uniform1f(uni.selStart, startCol);
      gl.uniform1f(uni.selEnd, endCol);
    }
  };
}

// ---------- Alignment (main scrollable) renderer ----------
function initAlignmentRenderer(canvas, alignPanel, spacer, config) {
  const dpr = window.devicePixelRatio || 1;
  let { w: CELL_W, h: CELL_H } = config.getCellDims();
  let rows = config.getRecords().length;
  let cols = config.getColCount();

  function sizeCanvasAndSpacer() {
    canvas.width = alignPanel.clientWidth * dpr;
    canvas.height = alignPanel.clientHeight * dpr;
    canvas.style.width = alignPanel.clientWidth + "px";
    canvas.style.height = alignPanel.clientHeight + "px";
    spacer.style.width = `${cols * CELL_W}px`;
    spacer.style.height = `${rows * CELL_H}px`;
  }
  sizeCanvasAndSpacer();

  const gl = canvas.getContext("webgl2");
  if (!gl) {
    alert("WebGL2 not supported");
    return {
      onScroll() {},
      onResize() {},
      rebuildBuffer() {},
      setCellSize() {},
      setLuminance() {},
      setHoverCol() {},
      setHoverRow() {}
    };
  }

  const { prog, vao, atlasTex, instBuf, uni } = compileMsaProgram(gl);
  gl.useProgram(prog);
  gl.uniform2f(uni.cellSize, CELL_W * dpr, CELL_H * dpr);
  gl.uniform2f(uni.scroll, 0, 0);
  gl.uniform2f(uni.res, canvas.width, canvas.height);
  gl.uniform1f(uni.luminance, config.getLuminance());

  let instData, instanceCount, cellIndex;
  let currentScrollX = 0,
    currentScrollY = 0;
  let hoveredIdx = -1;

  function cellForFn(r, c) {
    const rec = config.getRecords()[r];
    const ch = rec.seq[c] || "-";
    const override = rec.charColors && rec.charColors[c];
    const color = override ? hexToRgbFloat(override) : config.getColor(r, c, ch);
    return { ch, color };
  }

  function buildInstanceData() {
    const records = config.getRecords();
    rows = records.length;
    cols = config.getColCount();

    if (config.getShadeMode() === "unique") {
      config.setUniqueColCounts(computeUniqueColumnCounts(records, cols));
    }
    if (config.getShadeMode() === "frequency" && config.recomputeFrequencyColumns) {
      config.recomputeFrequencyColumns(cols);
    }

    instanceCount = rows * cols;
    instData = buildInstanceArray(rows, cols, cellForFn);
    cellIndex = [];
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        cellIndex.push({ row: r, col: c, record: records[r] });
      }
    }
    gl.bindBuffer(gl.ARRAY_BUFFER, instBuf);
    gl.bufferData(gl.ARRAY_BUFFER, instData, gl.DYNAMIC_DRAW);
  }
  buildInstanceData();

  function pickCell(clientX, clientY) {
    const rect = canvas.getBoundingClientRect();
    const x = (clientX - rect.left) * dpr + currentScrollX;
    const y = (clientY - rect.top) * dpr + currentScrollY;
    const col = Math.floor(x / (CELL_W * dpr));
    const row = Math.floor(y / (CELL_H * dpr));
    if (row < 0 || row >= rows || col < 0 || col >= cols) return -1;
    return row * cols + col;
  }
  function colFromClientX(clientX) {
    const rect = canvas.getBoundingClientRect();
    const x = (clientX - rect.left) * dpr + currentScrollX;
    return Math.floor(x / (CELL_W * dpr));
  }

  function updateSelectionUniform() {
    gl.useProgram(prog);
    const lo = Math.min(selStartCol, selEndCol);
    const hi = Math.max(selStartCol, selEndCol);
    gl.uniform1f(uni.selStart, lo);
    gl.uniform1f(uni.selEnd, hi);
    if (config.onSelectionChange) config.onSelectionChange(lo, hi);
  }
  function clearSelection() {
    selStartCol = -1;
    selEndCol = -1;
    gl.useProgram(prog);
    gl.uniform1f(uni.selStart, -1);
    gl.uniform1f(uni.selEnd, -1);
    if (config.onSelectionChange) config.onSelectionChange(-1, -1);
  }

  let selStartCol = -1,
    selEndCol = -1,
    colSelecting = false;

  const EDGE_ZONE = 30; // px from canvas edge that triggers auto-scroll
  const AUTO_SCROLL_SPEED = 12; // px per tick
  let autoScrollDir = 0; // -1 left, 0 none, 1 right
  let autoScrollInterval = null;

  function startAutoScroll(dir) {
    if (autoScrollDir === dir) return;
    stopAutoScroll();
    autoScrollDir = dir;
    autoScrollInterval = setInterval(() => {
      config.onAutoScrollDelta(dir * AUTO_SCROLL_SPEED);
    }, 16);
  }
  function stopAutoScroll() {
    if (autoScrollInterval) {
      clearInterval(autoScrollInterval);
      autoScrollInterval = null;
    }
    autoScrollDir = 0;
  }

  canvas.addEventListener("mousemove", (e) => {
    const newIdx = pickCell(e.clientX, e.clientY);
    if (newIdx !== hoveredIdx) {
      if (hoveredIdx >= 0) instData[hoveredIdx * 7 + 5] = 0;
      if (newIdx >= 0) instData[newIdx * 7 + 5] = 1;
      hoveredIdx = newIdx;
      gl.bindBuffer(gl.ARRAY_BUFFER, instBuf);
      gl.bufferData(gl.ARRAY_BUFFER, instData, gl.DYNAMIC_DRAW);
      if (newIdx >= 0 && config.onHover) config.onHover(cellIndex[newIdx].row, cellIndex[newIdx].col);
      else if (newIdx < 0 && config.onHoverEnd) config.onHoverEnd();
    }
  });
  canvas.addEventListener("mouseleave", () => {
    if (hoveredIdx >= 0) {
      instData[hoveredIdx * 7 + 5] = 0;
      hoveredIdx = -1;
      gl.bindBuffer(gl.ARRAY_BUFFER, instBuf);
      gl.bufferData(gl.ARRAY_BUFFER, instData, gl.DYNAMIC_DRAW);
    }
    if (config.onHoverEnd) config.onHoverEnd();
  });

  canvas.addEventListener("click", (e) => {
    if (window._activeContextMenu) {
      closeContextMenu();
      return;
    }
    const i = pickCell(e.clientX, e.clientY);
    if (i < 0) return;
    const cell = cellIndex[i];
    if (!cell.record.charColors) cell.record.charColors = {};
    const currentChar = cell.record.seq[cell.col] || "-";
    const overrideHex = cell.record.charColors[cell.col];
    const currentColorHex = overrideHex || rgbFloatToHex(config.getColor(cell.row, cell.col, currentChar));
    showCellEditPopup(
      e.clientX,
      e.clientY,
      currentChar,
      currentColorHex,
      (newChar, newColorHex) => {
        let seq = cell.record.seq;
        if (seq.length <= cell.col) seq = seq.padEnd(cell.col + 1, "-");
        cell.record.seq = seq.substring(0, cell.col) + newChar + seq.substring(cell.col + 1);
        cell.record.charColors[cell.col] = newColorHex;
        applyColorOverrides([{ row: cell.row, col: cell.col, ch: newChar, color: hexToRgbFloat(newColorHex) }]);
        config.onDataChanged(cell.col);
      },
      () => {
        delete cell.record.charColors[cell.col];
        const ch = cell.record.seq[cell.col] || "-";
        applyColorOverrides([{ row: cell.row, col: cell.col, ch, color: config.getColor(cell.row, cell.col, ch) }]);
      }
    );
  });

  canvas.addEventListener("contextmenu", (e) => e.preventDefault());
  canvas.addEventListener("mousedown", (e) => {
    if (e.button !== 2) return;
    e.preventDefault();
    closeContextMenu();
    const col = colFromClientX(e.clientX);
    if (col < 0 || col >= cols) return;
    colSelecting = true;
    selStartCol = col;
    selEndCol = col;
    updateSelectionUniform();
  });
  window.addEventListener("mousemove", (e) => {
    if (!colSelecting) return;
    const col = colFromClientX(e.clientX);
    selEndCol = Math.max(0, Math.min(cols - 1, col));
    updateSelectionUniform();

    const rect = canvas.getBoundingClientRect();
    const distFromLeft = e.clientX - rect.left;
    const distFromRight = rect.right - e.clientX;
    if (distFromLeft >= 0 && distFromLeft < EDGE_ZONE) {
      startAutoScroll(-1);
    } else if (distFromRight >= 0 && distFromRight < EDGE_ZONE) {
      startAutoScroll(1);
    } else {
      stopAutoScroll();
    }
  });
  window.addEventListener("mouseup", (e) => {
    if (e.button !== 2 || !colSelecting) return;
    colSelecting = false;
    stopAutoScroll();
    const lo = Math.min(selStartCol, selEndCol),
      hi = Math.max(selStartCol, selEndCol);
    showColumnContextMenu(
      e.clientX,
      e.clientY,
      lo,
      hi,
      (lo2, hi2) => {
        config.onDeleteColumns(lo2, hi2);
        buildInstanceData();
        sizeCanvasAndSpacer();
      },
      (lo2, hi2, onModalClose) => config.onAnnotateColumns(lo2, hi2, onModalClose),
      (lo2, hi2, onModalClose) => config.onBlockShadeColumns(lo2, hi2, onModalClose),
      (lo2, hi2) => config.onGenerateLogo(lo2, hi2),
      (lo2, hi2) => config.onExportColumns(lo2, hi2),
      clearSelection
    );
  });
  // ---- Touch column selection: long-press then drag ----
  const LONG_PRESS_MS = 400;
  const MOVE_CANCEL_PX = 10;
  let touchSelTimer = null;
  let touchSelActive = false;
  let suppressNextClick = false;
  let touchStartX = 0,
    touchStartY = 0,
    lastTouchX = 0;
  let touchAutoScrollInterval = null;

  function stopTouchAutoScroll() {
    if (touchAutoScrollInterval) {
      clearInterval(touchAutoScrollInterval);
      touchAutoScrollInterval = null;
    }
  }
  function startTouchAutoScroll(dir) {
    stopTouchAutoScroll();
    touchAutoScrollInterval = setInterval(() => {
      config.onAutoScrollDelta(dir * AUTO_SCROLL_SPEED);
      // recompute the column under the (stationary) finger as content scrolls beneath it
      selEndCol = Math.max(0, Math.min(cols - 1, colFromClientX(lastTouchX)));
      updateSelectionUniform();
    }, 16);
  }

  canvas.addEventListener(
    "touchstart",
    (e) => {
      if (e.touches.length !== 1) return;
      const t = e.touches[0];
      touchStartX = t.clientX;
      touchStartY = t.clientY;
      lastTouchX = t.clientX;
      touchSelActive = false;
      touchSelTimer = setTimeout(() => {
        const col = colFromClientX(lastTouchX);
        if (col < 0 || col >= cols) return;
        touchSelActive = true;
        selStartCol = col;
        selEndCol = col;
        updateSelectionUniform();
        if (navigator.vibrate) navigator.vibrate(10);
      }, LONG_PRESS_MS);
    },
    { passive: true }
  );

  canvas.addEventListener(
    "touchmove",
    (e) => {
      const t = e.touches[0];
      if (!t) return;
      lastTouchX = t.clientX;
      if (!touchSelActive) {
        if (Math.abs(t.clientX - touchStartX) > MOVE_CANCEL_PX || Math.abs(t.clientY - touchStartY) > MOVE_CANCEL_PX) {
          clearTimeout(touchSelTimer);
          touchSelTimer = null;
        }
        return; // not selecting → let the scroll handlers work
      }
      e.preventDefault();
      e.stopPropagation(); // keep alignPanel's touch-scroll from fighting the selection
      selEndCol = Math.max(0, Math.min(cols - 1, colFromClientX(t.clientX)));
      updateSelectionUniform();
      const rect = canvas.getBoundingClientRect();
      const distFromLeft = t.clientX - rect.left;
      const distFromRight = rect.right - t.clientX;
      if (distFromLeft >= 0 && distFromLeft < EDGE_ZONE) startTouchAutoScroll(-1);
      else if (distFromRight >= 0 && distFromRight < EDGE_ZONE) startTouchAutoScroll(1);
      else stopTouchAutoScroll();
    },
    { passive: false }
  );

  canvas.addEventListener("touchend", (e) => {
    clearTimeout(touchSelTimer);
    touchSelTimer = null;
    if (!touchSelActive) return;
    touchSelActive = false;
    stopTouchAutoScroll();
    suppressNextClick = true; // a click fires after touchend — don't let it open the cell editor
    const t = e.changedTouches[0];
    const lo = Math.min(selStartCol, selEndCol);
    const hi = Math.max(selStartCol, selEndCol);
    showColumnContextMenu(
      t.clientX,
      t.clientY,
      lo,
      hi,
      (lo2, hi2) => {
        config.onDeleteColumns(lo2, hi2);
        buildInstanceData();
        sizeCanvasAndSpacer();
      },
      (lo2, hi2, onModalClose) => config.onAnnotateColumns(lo2, hi2, onModalClose),
      (lo2, hi2, onModalClose) => config.onBlockShadeColumns(lo2, hi2, onModalClose),
      (lo2, hi2) => config.onGenerateLogo(lo2, hi2),
      (lo2, hi2) => config.onExportColumns(lo2, hi2),
      clearSelection
    );
  });

  canvas.addEventListener("touchcancel", () => {
    clearTimeout(touchSelTimer);
    touchSelTimer = null;
    touchSelActive = false;
    stopTouchAutoScroll();
  });

  function render() {
    gl.viewport(0, 0, canvas.width, canvas.height);
    gl.clearColor(0.07, 0.07, 0.07, 1);
    gl.clear(gl.COLOR_BUFFER_BIT);
    gl.useProgram(prog);
    gl.activeTexture(gl.TEXTURE0);
    gl.bindTexture(gl.TEXTURE_2D, atlasTex);
    gl.bindVertexArray(vao);
    gl.drawArraysInstanced(gl.TRIANGLES, 0, 6, instanceCount);
    requestAnimationFrame(render);
  }
  render();

  function applyColorOverrides(hitList) {
    const colCount = config.getColCount();
    hitList.forEach(({ row, col, ch, color }) => {
      const idx = row * colCount + col;
      if (ch !== undefined) instData[idx * 7 + 6] = glyphIndexFor(ch);
      instData[idx * 7 + 2] = color[0];
      instData[idx * 7 + 3] = color[1];
      instData[idx * 7 + 4] = color[2];
    });
    gl.bindBuffer(gl.ARRAY_BUFFER, instBuf);
    gl.bufferData(gl.ARRAY_BUFFER, instData, gl.DYNAMIC_DRAW);
  }
  return {
    onScroll(scrollTop, scrollLeft) {
      currentScrollY = scrollTop * dpr;
      currentScrollX = scrollLeft * dpr;
      gl.useProgram(prog);
      gl.uniform2f(uni.scroll, currentScrollX, currentScrollY);
    },
    onResize() {
      sizeCanvasAndSpacer();
      gl.useProgram(prog);
      gl.uniform2f(uni.res, canvas.width, canvas.height);
    },
    rebuildBuffer() {
      buildInstanceData();
      sizeCanvasAndSpacer();
    },
    applyColorOverrides,
    setCellSize(newW, newH) {
      CELL_W = newW;
      CELL_H = newH;
      gl.useProgram(prog);
      gl.uniform2f(uni.cellSize, CELL_W * dpr, CELL_H * dpr);
      sizeCanvasAndSpacer();
    },
    setLuminance(val) {
      gl.useProgram(prog);
      gl.uniform1f(uni.luminance, val);
    },
    setHoverCol(col) {
      gl.useProgram(prog);
      gl.uniform1f(uni.hoverCol, col);
    },
    setHoverRow(row) {
      gl.useProgram(prog);
      gl.uniform1f(uni.hoverRow, row);
    }
  };
}

