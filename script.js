function computeShadeColorForMode(tabState, mode, row, col, ch) {
  switch (mode) {
    case "frequency": {
      const hit = computeFrequencyShadeColor(tabState, row, col, ch);
      return hit || [1, 1, 1];
    }
    case "unique":
      return computeUniqueShadeColor(tabState, col, ch);
    case "matrix":
      return computeMatrixShadeColor(tabState, row, col, ch);
    case "sequence":
      return computeSequenceShadeColor(tabState, row, col, ch);
    case "regex": {
      const hit = computeRegexShadeColor(tabState, row, col, ch);
      return hit || computeShadeColorForMode(tabState, tabState.shadeConfig.regex.baseMode || "standard", row, col, ch);
    }
    case "scanprosite": {
      const hit = computeScanPrositeShadeColor(tabState, row, col, ch);
      return (
        hit || computeShadeColorForMode(tabState, tabState.shadeConfig.scanprosite.baseMode || "standard", row, col, ch)
      );
    }
    default:
      return getColorForChar(tabState, ch);
  }
}

function getShadeColor(tabState, row, col, ch) {
  return computeShadeColorForMode(tabState, tabState.shadeMode, row, col, ch);
}

