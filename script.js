function activateTab(tabId, btnEl) {
  document.querySelectorAll(".tab-btn").forEach((b) => b.classList.remove("active"));
  document.querySelectorAll(".tab-panel").forEach((p) => p.classList.remove("active"));
  document.getElementById(tabId).classList.add("active");
  btnEl.classList.add("active");
}

function closeTab(tabId, btnEl) {
  const panel = document.getElementById(tabId);
  const wasActive = btnEl.classList.contains("active");
  btnEl.remove();
  panel.remove();
  if (wasActive) {
    const remaining = document.querySelectorAll(".tab-btn");
    if (remaining.length > 0)
      activateTab(remaining[remaining.length - 1].dataset.tabId, remaining[remaining.length - 1]);
  }
}

function reindexColumnMap(map, lo, hi) {
  const newMap = {};
  const removed = hi - lo + 1;
  Object.keys(map).forEach((k) => {
    const col = Number(k);
    if (col < lo) newMap[col] = map[col];
    else if (col > hi) newMap[col - removed] = map[col];
  });
  return newMap;
}

