let PROSITE_DB_CACHE = null;

async function loadPrositeDatabase() {
  if (PROSITE_DB_CACHE) return PROSITE_DB_CACHE;
  const res = await fetch("https://ftp.expasy.org/databases/prosite/prosite.dat");
  if (!res.ok) throw new Error("Failed to fetch prosite.dat: " + res.status);
  const text = await res.text();
  PROSITE_DB_CACHE = parsePrositeDat(text);
  return PROSITE_DB_CACHE;
}

function parsePrositeDat(text) {
  const lines = text.split(/\r?\n/);
  const entries = [];
  let cur = null;

  for (const line of lines) {
    if (line === "//") {
      if (cur && cur.isPattern && !cur.skip && cur.pattern) entries.push(cur);
      cur = null;
      continue;
    }
    const lineType = line.substring(0, 2);
    const lineData = line.substring(5);

    if (lineType === "ID") {
      const semi = lineData.indexOf(";");
      const name = lineData.substring(0, semi);
      const type = lineData
        .substring(semi + 1)
        .replace(".", "")
        .trim();
      cur = { name, accession: null, pattern: "", isPattern: type === "PATTERN", skip: false };
    } else if (!cur) {
      continue;
    } else if (lineType === "AC") {
      cur.accession = lineData.substring(0, lineData.indexOf(";"));
    } else if (lineType === "PA" && cur.isPattern) {
      const trimmed = lineData.trim();
      cur.pattern += trimmed.endsWith(".") ? trimmed.slice(0, -1) : trimmed;
    } else if (lineType === "CC") {
      if (lineData.includes("SKIP-FLAG=TRUE")) cur.skip = true;
    }
  }

  return entries
    .map((e) => {
      try {
        return { ...e, regex: prositePatternToRegex(e.pattern) };
      } catch (err) {
        return null;
      }
    })
    .filter(Boolean);
}

function prositePatternToRegex(pattern) {
  pattern = pattern.toUpperCase();

  if (pattern.startsWith("<{") && pattern.endsWith("}*>")) {
    const excluded = pattern.slice(2, pattern.indexOf("}"));
    return new RegExp(`^(?:(?![${excluded}]).)*$`);
  }

  const anchoredStart = pattern.startsWith("<");
  if (anchoredStart) pattern = pattern.slice(1);
  const anchoredEnd = pattern.endsWith(">");
  if (anchoredEnd) pattern = pattern.slice(0, -1);

  const tokens = pattern.split("-");
  let out = "";

  for (let tok of tokens) {
    let repeat = null;
    const parenIdx = tok.indexOf("(");
    if (parenIdx !== -1) {
      const inside = tok.substring(parenIdx + 1, tok.indexOf(")"));
      repeat = inside;
      tok = tok.substring(0, parenIdx);
    }

    let core;
    if (tok === "X") core = ".";
    else if (tok.startsWith("[")) core = `[${tok.slice(1, -1)}]`;
    else if (tok.startsWith("{")) core = `[^${tok.slice(1, -1)}]`;
    else if (tok.endsWith(">"))
      core = `[${tok.slice(0, -1)}]`; // rare C-term-in-bracket case, e.g. PS00267
    else core = tok.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

    if (repeat) {
      out += repeat.includes(",") ? `${core}{${repeat}}` : `${core}{${repeat}}`;
    } else {
      out += core;
    }
  }

  return new RegExp((anchoredStart ? "^" : "") + out + (anchoredEnd ? "$" : ""));
}

