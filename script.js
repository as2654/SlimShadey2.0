// ---------- Glyph atlas (supports upper + lowercase) ----------
const GLYPH_CHARSET = [];
for (let code = 32; code <= 126; code++) GLYPH_CHARSET.push(String.fromCharCode(code));
const charToGlyphIndex = new Map(GLYPH_CHARSET.map((c, i) => [c, i]));
const GLYPH_BLANK_INDEX = charToGlyphIndex.get(" ");
const GLYPH_FALLBACK_INDEX = charToGlyphIndex.get("?");

function glyphIndexFor(ch) {
  if (!ch || ch === " ") return GLYPH_BLANK_INDEX;
  if (charToGlyphIndex.has(ch)) return charToGlyphIndex.get(ch);
  const upper = ch.toUpperCase();
  if (charToGlyphIndex.has(upper)) return charToGlyphIndex.get(upper);
  return GLYPH_FALLBACK_INDEX;
}

function buildGlyphAtlas() {
  const cellPx = 64;
  const cols = Math.ceil(Math.sqrt(GLYPH_CHARSET.length));
  const rows = Math.ceil(GLYPH_CHARSET.length / cols);
  const canvas = document.createElement("canvas");
  canvas.width = cols * cellPx;
  canvas.height = rows * cellPx;
  const ctx = canvas.getContext("2d");
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  ctx.font = `bold ${Math.floor(cellPx * 0.92)}px 'Consolas', 'Unifont', 'DejaVu Sans Mono', monospace`;
  ctx.fillStyle = "#000000";
  ctx.textAlign = "center";
  ctx.textBaseline = "middle";
  GLYPH_CHARSET.forEach((ch, i) => {
    const col = i % cols;
    const row = Math.floor(i / cols);
    ctx.fillText(ch, col * cellPx + cellPx / 2, row * cellPx + cellPx / 2);
  });
  return { canvas, cols, rows };
}
