function getSubstitutionScore(matrixName, charA, charB) {
  const m = SUBSTITUTION_MATRICES[matrixName];
  if (!m) return 0;
  const a = charA.toUpperCase();
  const b = charB.toUpperCase();
  let i = m.order.indexOf(a);
  let j = m.order.indexOf(b);
  if (i === -1) i = m.order.indexOf("X");
  if (j === -1) j = m.order.indexOf("X");
  if (i === -1 || j === -1) return 0;
  return m.matrix[i][j];
}

// ---------- FASTA parsing ----------
function parseFasta(text) {
  const records = [];
  let current = null;
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line) continue;
    if (line.startsWith(">")) {
      if (current) records.push(current);
      current = { header: line.slice(1), seq: "" };
    } else if (current) {
      current.seq += line;
    }
  }
  if (current) records.push(current);
  records.forEach((r, i) => (r.id = i));
  return records;
}

