// ---------- Consensus computation ----------
function computeConsensus(records, colCount) {
  let result = "";
  for (let c = 0; c < colCount; c++) {
    const counts = new Map();
    for (const rec of records) {
      const ch = (rec.seq[c] || "-").toUpperCase();
      counts.set(ch, (counts.get(ch) || 0) + 1);
    }
    let best = "-",
      bestCount = -1;
    counts.forEach((count, ch) => {
      if (count > bestCount) {
        best = ch;
        bestCount = count;
      }
    });
    result += best;
  }
  return result;
}

function computeSimpleConsensusJava(tabState, colCount) {
  const alphaList = tabState.alphabet === "nucleotide" ? NUCLEOTIDE_ALPHABET : PROTEIN_ALPHABET;
  const charSet = alphaList.map((e) => e.code);
  const seqNum = tabState.records.length;
  const result = [];
  for (let c = 0; c < colCount; c++) {
    const counts = {};
    charSet.forEach((ch) => {
      counts[ch] = 0;
    });
    for (let k = 0; k < seqNum; k++) {
      const ch = (tabState.records[k].seq[c] || "-").toUpperCase();
      if (counts[ch] !== undefined) counts[ch]++;
    }
    let mostIncidences = [];
    let maxIncidenceCounter = 0;
    charSet.forEach((ch) => {
      if (counts[ch] === maxIncidenceCounter) {
        mostIncidences.push(ch);
      } else if (counts[ch] > maxIncidenceCounter) {
        maxIncidenceCounter = counts[ch];
        mostIncidences = [ch];
      }
    });
    const maxIncidenceRatio = maxIncidenceCounter / seqNum;
    const oneOffRatio = (seqNum - 1) / seqNum;
    if (mostIncidences.length === 1 && maxIncidenceRatio >= oneOffRatio) {
      result.push(mostIncidences[0]);
    } else if (mostIncidences.length === 1 && maxIncidenceRatio < oneOffRatio) {
      result.push(mostIncidences[0].toLowerCase());
    } else {
      result.push(" ");
    }
  }
  return result;
}

function computeDotsAndIdentityConsensus(tabState, colCount) {
  const seqNum = tabState.records.length;
  const result = [];
  for (let c = 0; c < colCount; c++) {
    const counts = {};
    for (let k = 0; k < seqNum; k++) {
      const ch = (tabState.records[k].seq[c] || "-").toUpperCase();
      counts[ch] = (counts[ch] || 0) + 1;
    }
    let maxFreq = 0;
    let identityChar = null;
    for (const ch of Object.keys(counts)) {
      const freq = counts[ch] / seqNum;
      if (freq > maxFreq) {
        maxFreq = freq;
        if (maxFreq === 1) {
          identityChar = ch;
          break;
        }
      }
    }
    let toUse = " ";
    if (identityChar !== null) toUse = identityChar;
    else if (maxFreq >= 0.25 && maxFreq < 0.5) toUse = ".";
    else if (maxFreq >= 0.5 && maxFreq < 0.75) toUse = ":";
    else if (maxFreq >= 0.75 && maxFreq < 1) toUse = "*";
    result.push(toUse);
  }
  return result;
}
